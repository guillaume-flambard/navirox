/**
 * The Detox harness the native capture driver installs into the prepared
 * fixture application. The prepared application is a scaffolded Navirox app,
 * which carries no test wiring of its own, so the harness brings its own
 * configuration, setup file and capture test.
 *
 * The capture test reads the scenario, the artifact directory and the platform
 * from the environment instead of duplicating them: the scenario stays the one
 * description of which actions run before which capture. Installing the
 * dependencies below is the caller's job, because only the caller knows how the
 * application is installed.
 */


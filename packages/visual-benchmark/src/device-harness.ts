const CAPTURE_TEST = `// Generated by the Navirox visual benchmark.
//
// One capture per run. The scenario path, the artifact directory, the platform,
// the device and the capture key all arrive through the environment, so this
// file holds no fixture knowledge: it drives the actions the scenario declares
// for this capture and writes one screenshot next to the web capture.
//
// The five temporal labels are the only moments a scenario may declare:
// rest, first-meaningful, midpoint, settled, interrupted.
import { copyFileSync, mkdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { by, device, element, waitFor } from 'detox'

const MOMENTS = ['rest', 'first-meaningful', 'midpoint', 'settled', 'interrupted']
const SETTLE_TIMEOUT = 120000

// The launch needs a budget of its own. jest applies its test timeout to hooks
// too, and on a runner the first Metro bundle takes minutes: a single stalled
// attempt spends the whole SETTLE_TIMEOUT, and jest would kill the run before
// the retry had a chance. The examples set the same kind of budget in beforeAll.
const HOOK_TIMEOUT = 480000

jest.setTimeout(HOOK_TIMEOUT)

interface DeclaredAction {
  press: string
  nth?: number
}

interface DeclaredCapture {
  key: string
  moment: string
  actions?: DeclaredAction[]
}

interface DeclaredScenario {
  name: string
  captures: DeclaredCapture[]
}

function required(name: string): string {
  const value = process.env[name]

  if (value === undefined || value === '') {
    throw new Error(
      name +
        ' is not set, so this run cannot know which capture to take. The capture driver sets it.',
    )
  }

  return value
}

const platform = required('NAVIROX_PLATFORM')
const scenarioPath = required('NAVIROX_SCENARIO')
const artifacts = required('NAVIROX_ARTIFACTS')
const captureKey = required('NAVIROX_CAPTURE')
const rootTestId = required('NAVIROX_ROOT_ID')

// Identifiers the scenario declares. They are asserted after the declared
// actions so a screen that did not render fails the capture instead of being
// handed to the comparison as if it had.
const identifiers = (process.env.NAVIROX_IDENTIFIERS ?? '')
  .split(',')
  .map((identifier) => identifier.trim())
  .filter((identifier) => identifier.length > 0)

const scenario = JSON.parse(readFileSync(scenarioPath, 'utf8')) as DeclaredScenario
const capture = scenario.captures.find((entry) => entry.key === captureKey)

if (capture === undefined) {
  throw new Error(
    'The scenario ' + scenario.name + ' declares no capture named ' + captureKey + '.',
  )
}

if (!MOMENTS.includes(capture.moment)) {
  throw new Error(
    'The capture ' +
      captureKey +
      ' declares the moment ' +
      capture.moment +
      ', which is not one of ' +
      MOMENTS.join(', ') +
      '.',
  )
}

// The renderer registers an idling resource while the first bundle arrives, so
// synchronization is switched off for the launch and switched back on once the
// screen is up. Every wait below then covers the render it precedes.
async function launchAndSettle(): Promise<void> {
  let lastError: unknown

  await device.launchApp({
    newInstance: true,
    launchArgs: { detoxEnableSynchronization: 0 },
  })

  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      await device.disableSynchronization()
      await waitFor(element(by.id(rootTestId)))
        .toExist()
        .withTimeout(SETTLE_TIMEOUT)

      return
    } catch (error) {
      lastError = error
    }
  }

  throw lastError
}

// A test identifier that appears several times has to be indexed: Detox refuses
// an element matcher that matches more than one view, so the first match is
// addressed explicitly instead of relying on an implicit choice.
function target(action: DeclaredAction) {
  return element(by.id(action.press)).atIndex(action.nth ?? 0)
}

// The launch is a hook rather than the first line of the test so it can spend
// the larger budget above without eating the test's own timeout.
beforeAll(launchAndSettle, HOOK_TIMEOUT)

it('captures ' + captureKey + ' on ' + platform, async () => {
  for (const action of capture.actions ?? []) {
    await waitFor(target(action))
      .toExist()
      .withTimeout(SETTLE_TIMEOUT)
    await target(action).tap()
  }

  await device.enableSynchronization()
  await waitFor(element(by.id(rootTestId)))
    .toExist()
    .withTimeout(SETTLE_TIMEOUT)

  for (const identifier of identifiers) {
    await waitFor(element(by.id(identifier)))
      .toExist()
      .withTimeout(SETTLE_TIMEOUT)
  }

  mkdirSync(artifacts, { recursive: true })

  const source = await device.takeScreenshot(
    scenario.name + '-' + captureKey + '-' + platform,
  )
  const destination = join(artifacts, captureKey + '.' + platform + '.png')

  copyFileSync(source, destination)

  console.log('captured ' + capture.moment + ' to ' + destination)
})
`


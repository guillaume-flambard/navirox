/**
 * Build scripts the harness needs settled. pnpm refuses to run a dependency's
 * build script it has not been told about, and an undecided script fails the
 * install rather than degrading, so every script the prepared application
 * encounters has to be decided here the same way the repository decides it.
 * Detox's postinstall builds the local iOS framework and the XCUITest runner
 * and patches its Android build to the app's React Native version, so the e2e
 * harness needs it; it is a no-op off darwin, so Linux CI is unaffected.
 */
export const DEVICE_HARNESS_ALLOW_BUILDS: Readonly<Record<string, boolean>> = {
  detox: true,
  // bunyan's optional dtrace provider compiles a native node-gyp module the
  // logger already treats as optional; skipping the compile loses nothing.
  'dtrace-provider': false,
  // The resolver's postinstall only wires up the prebuilt platform binding.
  'unrs-resolver': true,
}


/**
 * Approves the harness build scripts in the prepared application's package
 * manager settings. The settings file already exists in a scaffolded app, so
 * the entries are merged into the existing list instead of replacing it: a
 * scaffolded app declines its own watcher build for a reason, and dropping that
 * line would change the application, not the harness.
 */
export function allowDeviceHarnessBuilds(appDirectory: string): void {
  const settingsPath = join(appDirectory, 'pnpm-workspace.yaml')
  const lines = readFileSync(settingsPath, 'utf8').split('\n')
  const entries = Object.entries(DEVICE_HARNESS_ALLOW_BUILDS).map(
    ([name, allowed]) => `  '${name}': ${allowed ? 'true' : 'false'}`,
  )
  const header = lines.findIndex((line) => line.trimEnd() === 'allowBuilds:')

  if (header === -1) {
    writeFileSync(
      settingsPath,
      `${lines.join('\n').trimEnd()}\nallowBuilds:\n${entries.join('\n')}\n`,
      'utf8',
    )

    return
  }

  const merged = [...entries.filter((entry) => !lines.some((line) => line.trimEnd() === entry))]

  lines.splice(header + 1, 0, ...merged)
  writeFileSync(settingsPath, lines.join('\n'), 'utf8')
}

const ANDROID_DEFAULT_CONFIG_LINES: readonly string[] = [
  "testBuildType System.getProperty('testBuildType', 'debug')",
  "testInstrumentationRunner 'androidx.test.runner.AndroidJUnitRunner'",
  "missingDimensionStrategy 'detox', 'full'",
]

const ANDROID_DEPENDENCY_LINES: readonly string[] = ["androidTestImplementation('com.wix:detox:+')"]

/**
 * The Android test entrypoint Detox drives. `detox test` installs the
 * application plus this test APK and runs it on the emulator. Without it the
 * test APK falls back to the legacy runner, which scans every dex entry and
 * blocks the application before Detox can connect.
 */
export function detoxTestSource(namespace: string): string {
  return `package ${namespace};

import com.wix.detox.Detox;
import com.wix.detox.config.DetoxConfig;

import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;

import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.filters.LargeTest;
import androidx.test.rule.ActivityTestRule;

@RunWith(AndroidJUnit4.class)
@LargeTest
public class DetoxTest {
    @Rule
    public ActivityTestRule<MainActivity> mActivityRule =
            new ActivityTestRule<>(MainActivity.class, false, false);

    @Test
    public void runDetoxTests() {
        DetoxConfig detoxConfig = new DetoxConfig();
        detoxConfig.idlePolicyConfig.masterTimeoutSec = 90;
        detoxConfig.idlePolicyConfig.idleResourceTimeoutSec = 60;
        detoxConfig.rnContextLoadTimeoutSec = (BuildConfig.DEBUG ? 180 : 60);
        Detox.runTests(mActivityRule, detoxConfig);
    }
}
`
}

function insertBeforeBlockEnd(text: string, blockHeader: string, lines: readonly string[]): string {
  const all = text.split('\n')
  const start = all.findIndex((line) => line.trimStart().startsWith(blockHeader))

  if (start === -1) {
    throw new Error(`The application build file has no ${blockHeader} block to patch.`)
  }

  const indent = /^\s*/.exec(all[start] ?? '')?.[0] ?? ''
  const closing = `${indent}}`

  for (let index = start + 1; index < all.length; index += 1) {
    if (all[index] === closing) {
      all.splice(index, 0, ...lines.map((line) => `${indent}    ${line}`))

      return all.join('\n')
    }
  }

  throw new Error(`The ${blockHeader} block in the application build file is not closed.`)
}

function insertAfterBlockStart(
  text: string,
  blockHeader: string,
  lines: readonly string[],
): string {
  const all = text.split('\n')
  const start = all.findIndex((line) => line.trimStart().startsWith(blockHeader))

  if (start === -1) {
    throw new Error(`The application root build file has no ${blockHeader} block to patch.`)
  }

  const indent = /^\s*/.exec(all[start] ?? '')?.[0] ?? ''

  all.splice(start + 1, 0, ...lines.map((line) => `${indent}    ${line}`))

  return all.join('\n')
}

function insertInNestedBlock(
  text: string,
  outerHeader: string,
  innerHeader: string,
  lines: readonly string[],
): string {
  const all = text.split('\n')
  const outer = all.findIndex((line) => line.trimStart().startsWith(outerHeader))

  if (outer === -1) {
    throw new Error(`The application root build file has no ${outerHeader} block to patch.`)
  }

  const inner = all.findIndex(
    (line, index) => index > outer && line.trimStart().startsWith(innerHeader),
  )

  if (inner === -1) {
    throw new Error(`The application root build file has no ${innerHeader} block to patch.`)
  }

  const indent = /^\s*/.exec(all[inner] ?? '')?.[0] ?? ''
  const closing = `${indent}}`

  for (let index = inner + 1; index < all.length; index += 1) {
    if (all[index] === closing) {
      all.splice(index, 0, ...lines.map((line) => `${indent}    ${line}`))

      return all.join('\n')
    }
  }

  throw new Error(`The ${innerHeader} block in the application root build file is not closed.`)
}

/**
 * The root build file of the scaffolded application resolves no Detox artifact:
 * it carries neither the gradle script that declares the flavor dimension Detox's
 * AAR is published in, nor the repository that holds that AAR. Without both, the
 * androidTest dependency cannot resolve, so `assembleAndroidTest` fails and no
 * test APK is produced at all.
 */
function patchAndroidRootBuild(text: string): string {
  let patched = text

  if (!patched.includes('detox/android/rninfo.gradle')) {
    patched = insertAfterBlockStart(patched, 'buildscript {', [
      "// Detox (e2e): rninfo.gradle exposes the RN version metadata Detox's AAR reads.",
      '// The harness installs detox as a devDependency, so it sits under ./node_modules.',
      'apply from: "../node_modules/detox/android/rninfo.gradle"',
    ])
  }

  if (!patched.includes('detox/Detox-android')) {
    patched = insertInNestedBlock(patched, 'allprojects {', 'repositories {', [
      "// Detox's Android AAR, resolved from the node_modules detox the harness installs.",
      'maven { url "$rootDir/../node_modules/detox/Detox-android" }',
    ])
  }

  return patched
}

/**
 * Writes the Android test wiring the scaffolded application does not carry, the
 * same way it approves the build scripts. A Detox run needs a test APK that
 * starts the instrumentation, and the template ships neither an androidTest
 * source set nor the Detox test dependency, so `assembleAndroidTest` produced an
 * empty APK and the instrumentation never reported ready. The root build file is
 * patched too, because that dependency cannot resolve without the Detox gradle
 * script and the repository that holds the Detox AAR.
 */
export function writeAndroidTestWiring(appDirectory: string): readonly string[] {
  const buildFile = join(appDirectory, 'android', 'app', 'build.gradle')
  const text = readFileSync(buildFile, 'utf8')
  const namespace = /namespace\s+"([^"]+)"/.exec(text)?.[1]

  if (namespace === undefined) {
    throw new Error(
      `The application build file at ${buildFile} declares no namespace, so the Detox test class has no package.`,
    )
  }

  const testFile = join(
    appDirectory,
    'android',
    'app',
    'src',
    'androidTest',
    'java',
    ...namespace.split('.'),
    'DetoxTest.java',
  )

  mkdirSync(dirname(testFile), { recursive: true })
  writeFileSync(testFile, detoxTestSource(namespace), 'utf8')

  let patched = text

  if (!patched.includes('testInstrumentationRunner')) {
    patched = insertBeforeBlockEnd(patched, 'defaultConfig {', ANDROID_DEFAULT_CONFIG_LINES)
  }

  if (!patched.includes('androidTestImplementation')) {
    patched = insertBeforeBlockEnd(patched, 'dependencies {', ANDROID_DEPENDENCY_LINES)
  }

  writeFileSync(buildFile, patched, 'utf8')

  const rootBuildFile = join(appDirectory, 'android', 'build.gradle')
  const rootText = readFileSync(rootBuildFile, 'utf8')

  writeFileSync(rootBuildFile, patchAndroidRootBuild(rootText), 'utf8')

  return [testFile, buildFile, rootBuildFile]
}

/**
 * Writes the harness into the prepared application. Existing files are
 * overwritten, because the harness is generated output and a stale copy would
 * silently run a different test than the one this package describes.
 */
export function writeDeviceHarness(appDirectory: string): readonly string[] {
  const written: string[] = []

  for (const name of DEVICE_HARNESS_FILES) {
    const contents = HARNESS_CONTENTS[name]

    if (contents === undefined) {
      throw new Error(`The device harness has no contents for ${name}.`)
    }

    const path = join(appDirectory, name)

    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, contents, 'utf8')
    written.push(path)
  }

  allowDeviceHarnessBuilds(appDirectory)
  written.push(...writeAndroidTestWiring(appDirectory))

  return written
}

/**
 * The contents of one harness file, for tests and for review. A bare file name
 * is accepted as well as the path relative to the application, because the
 * caller usually knows the file rather than where it sits.
 */
export function deviceHarnessFile(name: string): string {
  const direct = HARNESS_CONTENTS[name]

  if (direct !== undefined) {
    return direct
  }

  const match = DEVICE_HARNESS_FILES.find((file) => file.endsWith(`/${name}`))
  const contents = match === undefined ? undefined : HARNESS_CONTENTS[match]

  if (contents === undefined) {
    throw new Error(`The device harness has no file named ${name}.`)
  }

  return contents
}
